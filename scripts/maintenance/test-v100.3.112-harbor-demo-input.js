"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),os=require("node:os"),path=require("node:path");
const {HarborPointDemoService}=require("../../server/services/harborPointDemoService");
const dir=fs.mkdtempSync(path.join(os.tmpdir(),"bc-harbor-demo-input-"));
(async()=>{try{
 const service=new HarborPointDemoService(path.join(dir,"fictional-demo.json"));
 const book=async(name,phone,time)=>service.create({version:(await service.snapshot()).version,guestName:name,phone,time,holidayEvent:"Thanksgiving",partySize:2});
 const numbered=(await book("Demo Guest 1","732-555-0123","17:30")).result;
 await assert.rejects(()=>book("Demo Guest 2","732-555-012","17:30"),e=>e.code==="INVALID_DEMO_PHONE"&&e.message.includes("0123"));
 await assert.rejects(()=>book("Real Guest","732-555-0124","17:30"),e=>e.code==="INVALID_DEMO_NAME");
 const cancelled=(await book("Demo Guest 2","732-555-0124","17:30")).result;
 await service.action({version:(await service.snapshot()).version,reservationId:cancelled.id,action:"cancel"});
 const completed=(await book("Demo Guest 3","732-555-0125","18:00")).result;
 await service.action({version:(await service.snapshot()).version,reservationId:completed.id,action:"arrive"});
 const table=(await service.snapshot()).tables[0];
 await service.action({version:(await service.snapshot()).version,reservationId:completed.id,action:"seat",tableId:table.id});
 await service.action({version:(await service.snapshot()).version,reservationId:completed.id,action:"complete"});
 const before=await service.snapshot();
 await assert.rejects(()=>service.clearHistory({version:before.version-1}),e=>e.statusCode===412);
 const cleared=await service.clearHistory({version:before.version});assert.equal(cleared.result.removed,2);
 const after=await new HarborPointDemoService(path.join(dir,"fictional-demo.json")).snapshot();
 assert.deepEqual(after.reservations.map(r=>r.id),[numbered.id]);
 assert.equal(after.tables[0].status,"cleaning");assert.equal(after.tables[0].reservationId,null);
 await service.ready({version:after.version,tableId:table.id});
 const router=fs.readFileSync(path.join(__dirname,"../../server/api/router.js"),"utf8");
 assert(router.includes('url.pathname==="/api/harbor-point-demo/clear-history"')&&router.includes('authService.can(auth,"write")'));
 const html=fs.readFileSync(path.join(__dirname,"../../client/harbor-point.html"),"utf8");
 assert(html.includes('id="clearDemoHistory"')&&html.includes("Active bookings and the live restaurant database are preserved."));
 console.log("V100.3.112 demo booking input and manager history clear passed: numbered names, specific validation, stale guard, terminal-only clear, active and cleaning truth retained, restart.");
}finally{fs.rmSync(dir,{recursive:true,force:true});}})().catch(e=>{console.error(e);process.exitCode=1});
