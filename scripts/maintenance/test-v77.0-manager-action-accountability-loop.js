"use strict";
const assert=require("assert"),fs=require("fs"),os=require("os"),path=require("path");
const root=path.resolve(__dirname,"../..");
const pkg=require(path.join(root,"package.json"));
const {createPersistence}=require(path.join(root,"server/persistence/persistenceFactory"));
const Actions=require(path.join(root,"server/services/commandManagerActionService"));
(async()=>{
 assert.equal(pkg.version,"77.0.0");
 const router=fs.readFileSync(path.join(root,"server/api/router.js"),"utf8");
 const server=fs.readFileSync(path.join(root,"server/server.js"),"utf8");
 const shell=fs.readFileSync(path.join(root,"client/js/modules/hospitalityOsShell.js"),"utf8");
 const html=fs.readFileSync(path.join(root,"client/index.html"),"utf8");
 for(const route of ["/api/command/actions","/api/command/actions/"])assert(router.includes(route));
 assert(server.includes("CommandManagerActionService"));
 assert(html.includes('id="bcAcknowledgeTop"'));
 assert(html.includes('id="bcManagerActionList"'));
 assert(shell.includes("acknowledgeTopPriority"));
 assert(shell.includes("updateManagerAction"));
 assert(shell.includes('method:"POST"'));
 assert(shell.includes('method:"PATCH"'));
 assert(shell.includes("X-Blue-Current-Idempotency-Key"));

 const dir=fs.mkdtempSync(path.join(os.tmpdir(),"bc-v77-")),dbPath=path.join(dir,"db.json");
 fs.writeFileSync(dbPath,JSON.stringify({organizations:[{id:"o"}],locations:[{id:"l",organizationId:"o",name:"Pilot"}],auditLogs:[],commandManagerActions:[]},null,2));
 const db=createPersistence({driver:"json",databasePath:dbPath,options:{logger:{warn(){},error(){}}}});
 const audits=[],events=[];
 const audit={record:async x=>{audits.push(x);return x;}},realtime={publish:(type,payload)=>events.push({type,payload})};
 let active=true;
 const command={snapshot:async()=>({dataMode:"live-current",location:{id:"l",name:"Pilot"},prioritization:{topPriorities:active?[{id:"priority_1",rank:1,score:91,domain:"kitchen",workspace:"kitchen",severity:"high",title:"Kitchen throughput needs attention",detail:"Ready food and held ticket.",recommendation:"Review Kitchen.",owner:"Manager + Expo",confidence:{label:"HIGH",score:92}}]:[]}})};
 const svc=new Actions(db,audit,realtime,command);
 const created=await svc.createFromPriority("o",["l"],{locationId:"l",priorityId:"priority_1",note:"Taking this."},"Manager One");
 assert.equal(created.status,"acknowledged");
 assert.equal(created.owner,"Manager + Expo");
 assert.equal(created.automaticAction,false);
 const duplicate=await svc.createFromPriority("o",["l"],{locationId:"l",priorityId:"priority_1"},"Manager One");
 assert.equal(duplicate.duplicate,true);
 assert.equal((await db.read()).commandManagerActions.length,1);
 const assigned=await svc.update("o",["l"],created.id,{action:"assign",owner:"Expo Lead",note:"Own expo."},"Manager One");
 assert.equal(assigned.owner,"Expo Lead");
 assert.equal(assigned.status,"assigned");
 const started=await svc.update("o",["l"],created.id,{action:"start"},"Expo Lead");
 assert.equal(started.status,"in_progress");
 const resolved=await svc.update("o",["l"],created.id,{action:"resolve",outcome:"Ready food ran and held ticket cleared."},"Expo Lead");
 assert.equal(resolved.status,"resolved");
 assert(resolved.resolvedAt);
 assert.equal(resolved.outcome,"Ready food ran and held ticket cleared.");
 await assert.rejects(()=>svc.update("o",["l"],created.id,{action:"start"},"Manager One"),e=>e.statusCode===409);
 const summary=await svc.summary("o",["l"],"l");
 assert.equal(summary.counts.open,0);assert.equal(summary.counts.resolved,1);assert.equal(summary.recentClosed.length,1);
 active=false;
 await assert.rejects(()=>svc.createFromPriority("o",["l"],{locationId:"l",priorityId:"priority_1"},"Manager One"),e=>e.code==="PRIORITY_NO_LONGER_ACTIVE");
 await assert.rejects(()=>svc.createFromPriority("o",["other"],{locationId:"l",priorityId:"priority_1"},"Manager One"),e=>e.statusCode===403);
 assert(audits.length>=4);assert(events.some(x=>x.type==="command:action-created"));assert(events.some(x=>x.type==="command:action-updated"));
 console.log(JSON.stringify({ok:true,version:"77.0.0",priorityAcknowledgement:true,duplicateOpenActionSuppressed:true,assignment:true,start:true,resolution:true,outcome:true,timeline:true,closedActionGuard:true,stalePriorityGuard:true,tenantLocationScope:true,auditTrail:true,realtime:true,humanAccountability:true,automaticAction:false},null,2));
})().catch(e=>{console.error(e);process.exit(1)});
