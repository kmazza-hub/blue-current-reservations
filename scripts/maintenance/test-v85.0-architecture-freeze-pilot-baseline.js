"use strict";
const assert=require("assert"),fs=require("fs"),path=require("path");
const root=path.resolve(__dirname,"../.."),pkg=require(path.join(root,"package.json"));
const Freeze=require(path.join(root,"server/services/architectureFreezeService"));
(()=>{
 assert.equal(pkg.version,"85.0.0");
 const router=fs.readFileSync(path.join(root,"server/api/router.js"),"utf8");
 const server=fs.readFileSync(path.join(root,"server/server.js"),"utf8");
 assert(router.includes('"/api/system/architecture-baseline"'));
 assert(server.includes("ArchitectureFreezeService"));
 const manifest=JSON.parse(fs.readFileSync(path.join(root,"config/architecture-freeze-v85.json"),"utf8"));
 assert.equal(manifest.status,"ARCHITECTURE_FROZEN");
 const out=new Freeze().build();
 assert.equal(out.version,"85.0.0");
 assert.equal(out.status,"ARCHITECTURE_FROZEN");
 assert.equal(out.baseline,"PILOT_BUILD_BASELINE");
 assert(out.domains.length>=12);
 assert.equal(new Set(out.domains.map(x=>x.domain)).size,out.domains.length);
 assert.equal(out.rules.newMajorCapabilityRequiresPilotEvidence,true);
 assert.equal(out.rules.duplicateDomainAuthorityProhibited,true);
 assert.equal(out.rules.duplicateWritePathsProhibited,true);
 assert.equal(out.rules.integrationWorkAllowed,true);
 assert.equal(out.rules.configurationWorkAllowed,true);
 assert.equal(out.rules.uxSimplificationAllowed,true);
 assert.equal(out.rules.reliabilityAndSecurityWorkAllowed,true);
 assert.equal(out.rules.pilotDefectFixesAllowed,true);
 assert.equal(out.rules.autonomousProductionChanges,false);
 assert.deepEqual(out.postFreezePriorities,["INTEGRATION_READINESS","RESTAURANT_CONFIGURATION","COMMAND_FIRST_UX","SECURITY_RELIABILITY_RECOVERY","PILOT_CERTIFICATION"]);
 console.log(JSON.stringify({ok:true,version:"85.0.0",architectureFrozen:true,pilotBuildBaseline:true,authoritativeDomainMap:true,duplicateAuthorityProhibited:true,newMajorCapabilityRequiresPilotEvidence:true,postFreezeRoadmapLocked:true,autonomousProductionChanges:false},null,2));
})();
